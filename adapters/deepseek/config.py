"""dsh headless-profile overlay writer.

dsh resolves profiles from ``$DSH_HOME/profiles/<name>/``; a ``cordis.patch.yml``
overlay adjusts provider wiring for that profile. The file is a top-level YAML
array of cordis-plugin-include ``PatchOptions`` entries — ``{id, config}``
replaces the targeted config row wholesale, ``{id, disabled}`` toggles rows,
``{insert: [...]}`` appends rows (see ``applyPatches`` in dsh-app-boot).

The shim writes an overlay that points the ``llm-deepseek`` provider row
(``@deepseek-ai/dsh-llm-deepseek-api-key``, provider ``deepseek-official``) at
the gateway's Anthropic-messages endpoint and retargets
``agent-default-model`` to the run's model. ``DEEPSEEK_API_KEY`` /
``DEEPSEEK_BASE_URL`` env vars (set by the adapter) remain the provider's
documented credential/base-URL fallbacks when a patch layer declines volatile
fields.

Stdlib-only (runs inside the sandbox).
"""

from __future__ import annotations

from pathlib import Path

from adapters.common.runner import ShimConfig

_OVERLAY = """\
# Generated by adapters.deepseek — per-run gateway wiring overlay.
# cordis.patch.yml is a YAML array of loader patch entries; {{id, config}}
# REPLACES the row's whole config, so every field the row needs is restated.
- id: llm-deepseek
  config:
    baseURL: "{gateway_url}"
    apiKeyEnv: "DEEPSEEK_API_KEY"
    # dsh defaults maxTokens to 256k — every request would reserve 256k at
    # the gateway budget gate (default run budget is 200k) and instantly
    # 429. Clamp to a coding-task-sane output cap.
    maxTokens: {max_tokens}
- id: agent-default-model
  config:
    provider: deepseek-official
    model: "{model}"
"""


def dsh_home(cfg: ShimConfig) -> Path:
    return Path(cfg.env.get("DSH_HOME") or (Path(cfg.home) / ".dsh"))


def write_config(cfg: ShimConfig) -> Path:
    """Write ``$DSH_HOME/profiles/headless/cordis.patch.yml``; returns path."""
    home = dsh_home(cfg)
    profile_dir = home / "profiles" / "headless"
    profile_dir.mkdir(parents=True, exist_ok=True)
    path = profile_dir / "cordis.patch.yml"
    path.write_text(
        _OVERLAY.format(
            gateway_url=cfg.gateway_url.replace('"', '\\"'),
            model=cfg.model.replace('"', '\\"'),
            max_tokens=int(cfg.env.get("DSH_MAX_TOKENS") or "16384"),
        ),
        encoding="utf-8",
    )
    return path
