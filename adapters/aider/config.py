"""Aider ``.aider.conf.yml`` writer — points aider at the AI gateway.

Written inside the sandbox by the shim before ``aider`` starts. Aider
reads ``.aider.conf.yml`` from CWD, then the git root, then ``$HOME`` —
the shim targets ``$HOME`` so the workspace (and the artifact snapshot
built from it) stays free of harness bookkeeping.

The file carries everything the headless run needs except the credential
itself: the per-sandbox ``heg.*`` cred reaches litellm's openai provider
as ``OPENAI_API_KEY`` at request time (adapter env), so it never lands on
disk. ``openai-api-base`` + the ``openai/`` model prefix is aider's
documented route to OpenAI-compatible endpoints; the base URL needs the
``/v1`` suffix. ``weak-model`` — commit messages + chat-history
summarization — is pinned to the run's model: aider's built-in default is
a hosted model that would break both the egress lockdown and the
same-model comparison axis.

Chat/input/llm history files are relocated under ``$HOME`` for the same
reason as the conf file itself.

Stdlib-only (runs inside the sandbox).
"""

from __future__ import annotations

from pathlib import Path

from adapters.common.runner import ShimConfig


def _yaml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def aider_conf_path(cfg: ShimConfig) -> Path:
    return Path(cfg.home) / ".aider.conf.yml"


def conf_lines(cfg: ShimConfig) -> list[str]:
    """The ``.aider.conf.yml`` body (one ``key: value`` line per row)."""
    lines = [
        "# Generated by adapters.aider — per-run gateway wiring + headless hardening.",
        f"openai-api-base: {_yaml_str(cfg.gateway_url + '/v1')}",
    ]
    if cfg.model:
        lines += [
            f"model: {_yaml_str('openai/' + cfg.model)}",
            f"weak-model: {_yaml_str('openai/' + cfg.model)}",
        ]
    lines += [
        # Auto-confirm every prompt: add-file, dirty-commit, repo-create,
        # and the shell-command suggestions (how `done` gets invoked).
        "yes-always: true",
        # aider's native checkpoints — `Commit <sha>` events + a reviewable
        # git log inside the workspace artifact.
        "auto-commits: true",
        "dirty-commits: true",
        "suggest-shell-commands: true",
        # No non-gateway egress: never fetch URLs found in the prompt,
        # phone home for updates, or send analytics.
        "detect-urls: false",
        "check-update: false",
        "show-release-notes: false",
        "analytics-disable: true",
        # Line-stable plain output for the shim's translate_text hook;
        # stdin is DEVNULL.
        "pretty: false",
        "stream: false",
        "fancy-input: false",
        f"chat-history-file: {_yaml_str(str(Path(cfg.home) / '.aider.chat.history.md'))}",
        f"input-history-file: {_yaml_str(str(Path(cfg.home) / '.aider.input.history'))}",
        f"llm-history-file: {_yaml_str(str(Path(cfg.home) / '.aider.llm.history.txt'))}",
    ]
    return lines


def write_config(cfg: ShimConfig) -> Path:
    """Write ``$HOME/.aider.conf.yml``; returns the path written."""
    path = aider_conf_path(cfg)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(conf_lines(cfg)) + "\n", encoding="utf-8")
    return path
