"""Pi ``models.json`` writer — declares the ``heg`` provider.

``~/.pi/agent/models.json`` tells pi where compatible endpoints live
(packages/coding-agent/docs/models.md). ``apiKey: "$GATEWAY_CRED"`` is pi's
env interpolation — the per-sandbox cred never lands in a file, and pi reads
it at request time from the process env the shim inherits.

Stdlib-only (runs inside the sandbox).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from adapters.common.runner import ShimConfig


def pi_agent_dir(cfg: ShimConfig) -> Path:
    override = cfg.env.get("PI_CODING_AGENT_DIR")
    return Path(override) if override else Path(cfg.home) / ".pi" / "agent"


def models_json(cfg: ShimConfig) -> dict[str, Any]:
    return {
        "providers": {
            "heg": {
                "baseUrl": f"{cfg.gateway_url}/v1",
                "api": "openai-completions",
                "apiKey": "$GATEWAY_CRED",
                "models": [{"id": cfg.model}],
            }
        }
    }


#: Generated pi extension (PR17) — pi auto-discovers ``extensions/*.ts``
#: under the agent dir. The forwarder is observer-only: it spawns the shared
#: hook receiver per forwarded event (stdin JSON, env carries the ingest URL +
#: cred) and swallows every error so telemetry can never block or break the
#: agent loop. Only ``tool_execution_end`` is forwarded — its result payload
#: becomes a ``tool_result`` event; starts/turns/messages are already covered
#: by the ``--mode json`` stream, and duplicating them would double-count.
EXTENSION_FILENAME = "heg-events.ts"

_EXTENSION_TS = """\
// Generated by adapters.pi.config — forwards selected pi lifecycle events to
// the shared heg hook receiver (python3 -m adapters.common.hooks pi), which
// normalizes them and POSTs to EVENTS_INGEST_URL. Observer-only: handlers
// return nothing and swallow every error — telemetry must never block or
// break the agent.
import { execFileSync } from "node:child_process";

const RECEIVER_ARGS = ["-m", "adapters.common.hooks", "pi"];
const HOOK_TIMEOUT_MS = 10_000;

function forward(hookEventName: string): (event: unknown) => void {
  return (event: unknown) => {
    try {
      execFileSync("python3", RECEIVER_ARGS, {
        input: JSON.stringify({ hook_event_name: hookEventName, event }),
        stdio: ["pipe", "ignore", "ignore"],
        timeout: HOOK_TIMEOUT_MS,
      });
    } catch {
      // Telemetry must never propagate.
    }
  };
}

export default function (pi: {
  on: (name: string, handler: (event: unknown) => void) => unknown;
}): void {
  pi.on("tool_execution_end", forward("tool_execution_end"));
}
"""


def extension_path(cfg: ShimConfig) -> Path:
    return pi_agent_dir(cfg) / "extensions" / EXTENSION_FILENAME


def write_extension(cfg: ShimConfig) -> Path:
    """Write ``<agent_dir>/extensions/heg-events.ts``; returns the path."""
    path = extension_path(cfg)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_EXTENSION_TS, encoding="utf-8")
    return path


def write_config(cfg: ShimConfig) -> Path:
    """Write ``models.json`` + the hook-forwarding extension.

    Returns the ``models.json`` path (the provider config the shim exists
    for); the extension is a telemetry add-on, not startup-critical.
    """
    agent_dir = pi_agent_dir(cfg)
    agent_dir.mkdir(parents=True, exist_ok=True)
    path = agent_dir / "models.json"
    path.write_text(json.dumps(models_json(cfg), indent=2), encoding="utf-8")
    write_extension(cfg)
    return path
